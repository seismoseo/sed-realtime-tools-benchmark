#!/usr/bin/env python
# scrtdd_templates.py -- writes the working scrtdd configuration of the Gwangyang benchmark as templates for
#                        the later real-time test (runs/gwangyang/scrtdd/templates/).
#
# Usage (after 'source install/env_seiscomp.sh'; dry run by default):
#     python scrtdd_templates.py            # print the files it would write
#     python scrtdd_templates.py --apply    # write them, then let SeisComP's own reader parse them back
#
# Written files:
#   templates/global.cfg                       NonLinLoc travel times (tttnll plugin) + record stream
#   templates/scrtdd.cfg                       module + profile 'gwangyang' = the settings of run S1, with the
#                                              S1 relocated catalog as reference catalog and the real-time
#                                              switches (activeProfiles, messaging groups, accepted authors)
#   templates/reference_catalog/{event,phase,station}.csv   S1 positions of all 11 events (standard columns),
#                                              the 763 catalog picks and the 54 stations
#   templates/template_options.json            every value scrtdd would use with these files (resolved by
#                                              scrtdd_common.resolve_options, i.e. by seiscomp.config)
# Nothing here starts a SeisComP module or opens a port.

import argparse
import csv
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import scrtdd_common as C  # noqa: E402

# ----------------------------------------------------------------------------- parameters
TDIR = f"{C.RUNROOT}/templates"
REF_EVENT = f"{C.RUNROOT}/S1/work/reloc-event.csv"
LOCATOR_AUTHOR = "scautoloc@server-a"   # author string of the origins scrtdd should relocate (check in the test)
SDS = C.SDS_DIR

GLOBAL_TEMPLATE = f"""# global.cfg template for scrtdd (Gwangyang benchmark, step 08; generated by scrtdd_templates.py)
# Put it in the SEISCOMP_LOCAL_CONFIG folder of the real-time run (never in ~/.seiscomp).
# core.plugins = dbsqlite3 is already set in $SEISCOMP_ROOT/etc/global.cfg (dbmysql is not built).

# NonLinLoc kim1983 travel-time grids through scrtdd's plugin (SeisComP name "NLLGrid")
plugins = tttnll
ttt.NLLGrid.tables = kim1983
ttt.NLLGrid.kim1983.tablePath = {C.NLL_TABLEPATH}
# metres; 0.1 m = pyrtdd's default and enough for all 54 stations (the plugin default is 10 m)
ttt.NLLGrid.kim1983.maxSearchDistance = 0.1

# Offline (benchmark): waveforms from the SDS archive
recordstream = sdsarchive://{SDS}
# Real time: catalog waveforms from the archive, the new event from SeedLink on localhost; timeout and
# retries=0 stop scrtdd from waiting minutes for data that is not there (singleevent.rst, "Waveform Data").
# recordstream = combined://slink/localhost:18000?timeout=5&retries=0;sdsarchive//{SDS}
"""

MODULE_REALTIME = {
    # --- the switches to change for the real-time test ---------------------------------------------------
    "activeProfiles": "gwangyang",                 # empty = no real-time relocation at all
    # Loop protection (singleevent.rst "Avoiding Relocation Loops"): scrtdd listens to and sends to LOCATION.
    # Either accept only the automatic locator's origins (below) or send to a separate group RELOCATION,
    # which must then be added to scmaster's groups and to scevent's subscriptions.
    "acceptedOriginAuthors": LOCATOR_AUTHOR,
    "connection.primaryGroup": "LOCATION",
    "connection.subscriptions": "SERVICE_REQUEST, EVENT, LOCATION, PICK",
    # true = relocate only the preferred origin of an event (needs scevent running); false = every origin on LOCATION
    "onlyPreferredOrigins": "true",
    "automaticOrigins": "true",
    "manualOrigins": "true",
    # --- performance ----------------------------------------------------------------------------------------
    "performance.delayTime": "10",                 # s after an origin arrives (lets late picks come in)
    "performance.profileTimeAlive": "-1",          # keep the reference catalog (and its waveforms) loaded
    "performance.cacheWaveforms": "true",
    "performance.cacheDirectory": f"{C.PROJECT}/runs/realtime/rtdd_cache",   # change to the real-time run folder
    "performance.cachedWaveformLength": "10",
}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    profile = {**C.COMMON, **C.CLUSTERING_HYPODD_LIKE, **C.SOLVER_HYPODD_LIKE, **C.XCORR_LIKE_REFERENCE,
               "catalog.eventFile": f"{TDIR}/reference_catalog/event.csv",
               "catalog.phaFile": f"{TDIR}/reference_catalog/phase.csv",
               "catalog.stationFile": f"{TDIR}/reference_catalog/station.csv"}
    if not a.apply:
        print(GLOBAL_TEMPLATE)
        for k, v in {**MODULE_REALTIME, **{f"profile.{C.PROFILE}.{k}": v for k, v in profile.items()}}.items():
            print(f"{k} = {v}")
        print("dry run: nothing written (use --apply)")
        return
    os.makedirs(f"{TDIR}/reference_catalog", exist_ok=True)
    with open(REF_EVENT, newline="") as f:
        rows = list(csv.DictReader(f))
    with open(f"{TDIR}/reference_catalog/event.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["id", "isotime", "latitude", "longitude", "depth", "magnitude"],
                           extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    shutil.copyfile(C.PHASE_CSV, f"{TDIR}/reference_catalog/phase.csv")
    shutil.copyfile(C.STATION_CSV, f"{TDIR}/reference_catalog/station.csv")
    with open(f"{TDIR}/global.cfg", "w") as f:
        f.write(GLOBAL_TEMPLATE)
    # scrtdd.cfg: write_config() puts it into <dir>/seiscomp_user; write it there, then move it up
    header = ("scrtdd.cfg template for the real-time test (Gwangyang benchmark, step 08; scrtdd_templates.py)\n"
              "Profile 'gwangyang' = the settings of multi-event run S1; reference catalog = S1 relocation of\n"
              "the 11 events. Change: activeProfiles, acceptedOriginAuthors (or the messaging groups),\n"
              "performance.cacheDirectory and the recordstream in global.cfg; see notes_for_next_phase.")
    tmp = f"{TDIR}/_tmp"
    C.write_config(tmp, profile, module_values=MODULE_REALTIME, global_values=C.GLOBAL_CFG, header=header)
    shutil.move(f"{tmp}/seiscomp_user/scrtdd.cfg", f"{TDIR}/scrtdd.cfg")
    txt = open(f"{TDIR}/scrtdd.cfg").read().replace(
        "# (scrtdd.cfg of this run; SEISCOMP_LOCAL_CONFIG points here)",
        "# (copy into the SEISCOMP_LOCAL_CONFIG folder of the real-time run, next to global.cfg)")
    open(f"{TDIR}/scrtdd.cfg", "w").write(txt)
    shutil.rmtree(tmp)
    # parse the templates back with SeisComP's reader (as a run folder would see them)
    chk = f"{TDIR}/_check"
    os.makedirs(f"{chk}/seiscomp_user", exist_ok=True)
    shutil.copyfile(f"{TDIR}/global.cfg", f"{chk}/seiscomp_user/global.cfg")
    shutil.copyfile(f"{TDIR}/scrtdd.cfg", f"{chk}/seiscomp_user/scrtdd.cfg")
    resolved = C.resolve_options(chk, extra={"template_dir": TDIR, "reference_event_source": REF_EVENT,
                                             "generated": C.now_iso()})
    names, rc = C.print_config_vars(chk)
    resolved["print_config_vars_exit"] = rc
    resolved["print_config_vars_not_in_dump"] = C.check_print_config_vars(names, resolved)
    C.dump_json(f"{TDIR}/template_options.json", resolved)
    shutil.rmtree(chk)
    print("written:", sorted(os.listdir(TDIR)), "| print-config-vars exit", rc,
          "| not in dump:", resolved["print_config_vars_not_in_dump"])


if __name__ == "__main__":
    main()
