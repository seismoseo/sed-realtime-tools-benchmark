# 15_write_provenance.py -- reference/PROVENANCE.md: every downloaded file under
# data/sanramon_2026/reference with size, md5 and the request that produced it (looked up in
# logs/sanramon2026_requests.tsv by output path), plus md5 of the main derived inputs. Copied from
# the 2015 tool; files copied from data/sanramon_2015 (docs, TLS bundle) are marked as such, and the
# waveform folders (raw answers, SDS, playback: thousands of files) are summarised per folder.
# Usage: python -I 15_write_provenance.py

import csv
import datetime as dt
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sr_common as C  # noqa: E402


def md5(path):
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    req = {}
    with open(C.REQ_LOG) as f:
        for r in csv.DictReader(f, delimiter="\t"):
            if r["out_file"]:
                req[r["out_file"]] = r
    copied = set()
    cf = os.path.join(C.REF, "docs", "COPIED_FROM_2015.txt")
    if os.path.exists(cf):
        copied = {ln.split("\t")[0] for ln in open(cf).read().splitlines()[1:] if ln.strip()}
    lines = ["# Provenance of data/sanramon_2026/reference",
             "",
             f"Written {dt.datetime.now():%Y-%m-%d %H:%M} by tools/15_write_provenance.py. Every "
             "HTTP request (also failed ones) is in logs/sanramon2026_requests.tsv.",
             "Files without a request entry were made locally (unzipped, converted or extracted) or "
             "copied from data/sanramon_2015 (marked). Waveform folders are summarised per folder "
             "(their requests are in the same log and in each answer's .json manifest).",
             "",
             "| file | bytes | md5 | source (method URL, UTC time) |",
             "|---|---:|---|---|"]
    wf_dirs = {}
    for root, _, files in sorted(os.walk(C.REF)):
        relroot = os.path.relpath(root, C.REF)
        if relroot.startswith("waveforms_raw"):
            key = "/".join(relroot.split(os.sep)[:3])
            n, b = wf_dirs.get(key, (0, 0))
            wf_dirs[key] = (n + len(files), b + sum(os.path.getsize(os.path.join(root, f)) for f in files))
            continue
        for fn in sorted(files):
            p = os.path.join(root, fn)
            if fn == "PROVENANCE.md":
                continue
            rel = os.path.relpath(p, C.REF)
            r = req.get(p)
            if r:
                src = f"{r['method']} {r['url']} ({r['utc_time']})"
            elif relroot == "docs" and fn in copied:
                src = "copied from data/sanramon_2015/reference/docs (downloaded 2026-10-17)"
            elif relroot == "usgs_oaf":
                src = "placed here before this work package (ComCat); see usgs_oaf/PROVENANCE.md"
            elif relroot == os.path.join("ldeo", "tls"):
                src = "copied from data/sanramon_2015/reference/ldeo/tls (built 2026-10-17)"
            else:
                src = "local"
            if r and r["method"] == "POST" and r["form_or_params"] and len(r["form_or_params"]) < 400:
                src += f" form: {r['form_or_params']}"
            lines.append(f"| {rel} | {os.path.getsize(p)} | {md5(p)} | {src} |")
    if wf_dirs:
        lines += ["", "## Waveform answers (summary per folder)", "", "| folder | files | bytes |",
                  "|---|---:|---:|"]
        for k, (n, b) in sorted(wf_dirs.items()):
            lines.append(f"| {k} | {n} | {b} |")
    lines += ["", "## Derived inputs (data/sanramon_2026/inputs)", "", "| file | bytes | md5 |",
              "|---|---:|---|"]
    for root, _, files in sorted(os.walk(C.INP)):
        if os.sep + "time" in root or os.sep + "model" in root or os.sep + "sds" in root:
            continue                      # NonLinLoc grids (regenerated by make_nll_grids_tm.sh); SDS archive
        for fn in sorted(files):
            p = os.path.join(root, fn)
            lines.append(f"| {os.path.relpath(p, C.INP)} | {os.path.getsize(p)} | {md5(p)} |")
    with open(os.path.join(C.REF, "PROVENANCE.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(lines)} lines written")


if __name__ == "__main__":
    main()
