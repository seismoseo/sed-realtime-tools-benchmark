# 15_write_provenance.py -- reference/PROVENANCE.md: every downloaded file under
# data/sanramon_2015/reference with size, md5 and the request that produced it (looked up in
# logs/sanramon_requests.tsv by output path), plus md5 of the main derived inputs.
# Usage: python -I 15_write_provenance.py

import csv
import datetime as dt
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sr_common as C  # noqa: E402


def md5(path):
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    req = {}
    with open(C.REQ_LOG) as f:
        for r in csv.DictReader(f, delimiter="\t"):
            if r["out_file"]:
                req[r["out_file"]] = r
    lines = ["# Provenance of data/sanramon_2015/reference",
             "",
             f"Written {dt.datetime.now():%Y-%m-%d %H:%M} by tools/15_write_provenance.py. Every "
             "HTTP request (also failed ones) is in logs/sanramon_requests.tsv.",
             "Files without a request entry were made locally (unzipped, converted or extracted).",
             "",
             "| file | bytes | md5 | source (method URL, UTC time) |",
             "|---|---:|---|---|"]
    for root, _, files in sorted(os.walk(C.REF)):
        for fn in sorted(files):
            p = os.path.join(root, fn)
            if fn == "PROVENANCE.md":
                continue
            rel = os.path.relpath(p, C.REF)
            r = req.get(p)
            src = f"{r['method']} {r['url']} ({r['utc_time']})" if r else "local"
            if r and r["method"] == "POST" and r["form_or_params"] and len(r["form_or_params"]) < 400:
                src += f" form: {r['form_or_params']}"
            lines.append(f"| {rel} | {os.path.getsize(p)} | {md5(p)} | {src} |")
    lines += ["", "## Derived inputs (data/sanramon_2015/inputs)", "", "| file | bytes | md5 |",
              "|---|---:|---|"]
    for root, _, files in sorted(os.walk(C.INP)):
        if os.sep + "time" in root or os.sep + "model" in root:
            continue                      # NonLinLoc grids: too many, regenerated by make_nll_grids.sh
        for fn in sorted(files):
            p = os.path.join(root, fn)
            lines.append(f"| {os.path.relpath(p, C.INP)} | {os.path.getsize(p)} | {md5(p)} |")
    with open(os.path.join(C.REF, "PROVENANCE.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(lines)} lines written")


if __name__ == "__main__":
    main()
